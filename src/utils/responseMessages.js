/**
 * Looks up the friendly message for the route that is handling `req`.
 * Aliases mounted under /api/v1 (for example /api/v1/auth/login) reuse the message of the /api route.
 */
function messageForRoute(req) {
  if (!req || !req.route) return null;
  const path = `${req.baseUrl || ""}${req.route.path === "/" && req.baseUrl ? "/" : req.route.path}`;
  return (
    SUCCESS_MESSAGES[`${req.method} ${path}`] ||
    SUCCESS_MESSAGES[`${req.method} ${path.replace(/^\/api\/v1\//, "/api/")}`] ||
    null
  );
}

